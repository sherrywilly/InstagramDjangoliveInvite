def generate_device_id(seed):
    volatile_seed = "12345"
    m = hashlib.md5()
    m.update(seed.encode('utf-8') + volatile_seed.encode('utf-8'))
    return 'android-' + m.hexdigest()[:16]


def generate_signature(data, skip_quote=False):
    if not skip_quote:
        try:
            parsed_data = urllib.parse.quote(data)
        except AttributeError:
            parsed_data = urllib.quote(data)
    else:
        parsed_data = data
    return 'ig_sig_key_version=' + SIG_KEY_VERSION + '&signed_body=' + hmac.new(
        IG_SIG_KEY.encode('utf-8'), data.encode('utf-8'), hashlib.sha256).hexdigest() + '.' + parsed_data


